// Generates crawlable copies of index.html for each route, plus sitemap.xml, feed.xml,
// social share cards and app icons. Run after any change to index.html or posts/:
//   node scripts/build.mjs
// No dependencies. Content comes from the POSTS array in index.html's x-dc script block;
// posts with `md: true` take their body from posts/<id>.md (see scripts/markdown.mjs).
// Share cards and icons are rendered with headless Chrome (CHROME_PATH, default: the macOS app);
// without Chrome the build still succeeds and reuses existing images.
