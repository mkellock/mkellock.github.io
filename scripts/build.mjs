const MARK = '<!-- GENERATED by scripts/build.mjs from index.html. Do not edit; edit index.html and rebuild. -->';
const CHROME = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

